#!/usr/bin/env python3
"""Generate TeX trace macros directly from the committed reference code."""
import importlib.util
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
CODE = HERE.parent / "code" / "trees.py"
TARGET = HERE / "traces.tex"

spec = importlib.util.spec_from_file_location("trees_reference", CODE)
module = importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(module)


def tex_list(values):
    return ", ".join(str(value) for value in values)


content = """%% Generated by make_traces.py; do not edit by hand.
\\newcommand{\\TraceProjectPre}{%s}
\\newcommand{\\TraceProjectPost}{%s}
\\newcommand{\\TraceProjectBFS}{%s}
\\newcommand{\\TraceDecisionPre}{%s}
\\newcommand{\\TraceDecisionPost}{%s}
\\newcommand{\\TraceDecisionBFS}{%s}
\\newcommand{\\DroppedEdge}{\\texttt{requirements -> tests}}
""" % (
    tex_list(module.preorder("project", module.TREE_CHILDREN)),
    tex_list(module.postorder("project", module.TREE_CHILDREN)),
    tex_list(module.breadth_first("project", module.TREE_CHILDREN)),
    tex_list(module.decision_tree_traces()["preorder"]),
    tex_list(module.decision_tree_traces()["postorder"]),
    tex_list(module.decision_tree_traces()["breadth-first"]),
)

if "--check" in sys.argv:
    if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
        print("traces.tex differs from code/trees.py output")
        sys.exit(1)
    print("trace macros match code/trees.py")
else:
    TARGET.write_text(content, encoding="utf-8")
    print("wrote traces.tex from code/trees.py")
