#!/usr/bin/env python3
"""Compute every number the slides quote and write deck/numbers.tex (one \\newcommand per number).
Slides use the macros, never typed numbers.  Run: python3 scripts/make_numbers.py  (check_numbers.py verifies)."""
import math
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "code"))
from tour import (read_table, tour_length, legs, greedy_tour, guess_and_check,  # noqa: E402
                  brute_force, tour_count, expected_rolls)

GUESS_SEED = 3114   # fixed so the worked trace on the slides is reproducible


def build():
    D = read_table(root / "data" / "distances.csv")
    n = {}
    nat = [1, 2, 3, 4, 5, 6]
    for i, (a, b, d) in enumerate(legs(nat, D), 1):
        n[f"LegNat{i}"] = d
    n["TotalNat"] = tour_length(nat, D)
    rev = [1, 6, 5, 4, 3, 2]
    n["TotalRev"] = tour_length(rev, D)
    g = greedy_tour(D)
    n["GreedyTour"] = "-".join(map(str, g)) + "-1"
    n["GreedyTotal"] = tour_length(g, D)
    for i, (a, b, d) in enumerate(legs(g, D), 1):
        n[f"LegGreedy{i}"] = d
    best, bt, cnt = brute_force(D)
    n["BestTour"] = "-".join(map(str, best)) + "-1"
    n["BestTotal"] = bt
    for i, (a, b, d) in enumerate(legs(best, D), 1):
        n[f"LegBest{i}"] = d
    n["BruteCount"] = cnt
    n["PairsNat"] = pairs(nat)
    n["PairsRev"] = pairs(rev)
    n["PairsGreedy"] = pairs(g)
    n["PairsBest"] = pairs(best)
    n["GreedyGap"] = n["GreedyTotal"] - bt
    n["NatGap"] = n["TotalNat"] - bt
    # the sting: greedy's last leg
    n["GreedyLast"] = n["LegGreedy6"]
    # guess and check trace
    runs = guess_and_check(D, 5, seed=GUESS_SEED, with_rolls=True)
    for i, (t, tot, b, rolls) in enumerate(runs, 1):
        n[f"GTour{i}"] = "-".join(map(str, t)) + "-1"
        n[f"GTotal{i}"] = tot
        n[f"GBest{i}"] = b
        n[f"GRolls{i}"] = " ".join(map(str, rolls))
        n[f"GRejected{i}"] = len(rolls) - 5
    n["ERolls"] = f"{expected_rolls(6):.1f}"
    big = guess_and_check(D, 1000, seed=GUESS_SEED)
    n["G1000Best"] = big[-1][2]
    # counting
    for k in range(2, 7):
        n[f"Count{k}"] = tour_count(k)
        n[f"Fact{k}"] = math.factorial(k)
        n[f"Half{k}"] = tour_count(k) // 2 if k > 2 else 1
    n["Count15"] = f"{tour_count(15):,}".replace(",", r"\,")
    n["Count15raw"] = tour_count(15)
    n["Count10"] = f"{tour_count(10):,}".replace(",", r"\,")
    n["HoursAtMillion"] = f"{tour_count(15) / 1e6 / 3600:.1f}"
    return n


def macro_name(k):
    """TeX control words are letters only: digits become letters (1 -> One, 2 -> Two, ...)."""
    words = "Zero One Two Three Four Five Six Seven Eight Nine".split()
    return "N" + "".join(words[int(c)] if c.isdigit() else c for c in k)


def pairs(tour):
    """'1/3,3/5,...' list of legs of the closed tour, for the TikZ tour picture."""
    return ",".join(f"{tour[i]}/{tour[(i + 1) % len(tour)]}" for i in range(len(tour)))


def table_tex(D, tour=None, color="yellow!60"):
    """Body of a tabular for the distance table; cells used by `tour` (closed) are highlighted."""
    used = set()
    if tour:
        used = {(tour[i], tour[(i + 1) % len(tour)]) for i in range(len(tour))}
    out = ["\\begin{tabular}{c|cccccc}\n", "from $\\backslash$ to & 1 & 2 & 3 & 4 & 5 & 6\\\\\\hline\n"]
    for a in range(1, 7):
        cells = []
        for b in range(1, 7):
            if a == b:
                cells.append("\\cellcolor{black!12}")
            else:
                v = str(D[(a, b)])
                cells.append(f"\\cellcolor{{{color}}}\\textbf{{{v}}}" if (a, b) in used else v)
        out.append(f"\\textbf{{{a}}} & " + " & ".join(cells) + "\\\\\n")
    out.append("\\end{tabular}\n")
    return "".join(out)


def render(n):
    lines = ["% GENERATED by scripts/make_numbers.py -- do not edit\n"]
    for k, v in n.items():
        lines.append(f"\\newcommand{{\\{macro_name(k)}}}{{{v}}}\n")
    return "".join(lines)


if __name__ == "__main__":
    out = root / "deck" / "numbers.tex"
    out.write_text(render(build()))
    D = read_table(root / "data" / "distances.csv")
    g, (best, _, _) = greedy_tour(D), brute_force(D)
    for name, t in (("plain", None), ("nat", [1, 2, 3, 4, 5, 6]), ("greedy", g), ("best", best)):
        (root / "deck" / f"table_{name}.tex").write_text(table_tex(D, t))
    print(f"wrote {out} with {len(build())} numbers and 4 tables")
