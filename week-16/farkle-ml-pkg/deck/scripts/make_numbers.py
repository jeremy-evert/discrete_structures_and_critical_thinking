#!/usr/bin/env python3
"""Render all quoted fallback values from the validated CSV into TeX macros."""
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DECK = HERE.parent
PACKAGE = DECK.parent
CSV_PATH = PACKAGE.parent / "fallback" / "quick_v1_results.csv"


def read_rows():
    with CSV_PATH.open(newline="") as stream:
        rows = list(csv.DictReader(row for row in stream if not row.startswith("#")))
    rows.sort(key=lambda row: int(row["seed"]))
    if [int(row["seed"]) for row in rows] != [17, 2026, 6262]:
        raise ValueError("fallback CSV does not contain the expected three seeds")
    return rows


def tex_escape(value):
    return (
        str(value)
        .replace("\\", r"\textbackslash{}")
        .replace("_", r"\_")
        .replace("%", r"\%")
        .replace("&", r"\&")
        .replace("#", r"\#")
    )


def pct(wins, games):
    return f"{100 * int(wins) / int(games):g}\\%"


def difference(row):
    return 100 * (int(row["wins_a"]) - int(row["wins_b"])) / int(row["games"])


def integer(value):
    number = float(value)
    return str(int(number)) if number.is_integer() else f"{number:g}"


def macro_name(value):
    words = "Zero One Two Three Four Five Six Seven Eight Nine".split()
    return "N" + "".join(words[int(char)] if char.isdigit() else char for char in str(value))


def row_name(index):
    return ("One", "Two", "Three")[index]


def render_numbers(rows):
    initial = next(row for row in rows if int(row["seed"]) == 17)
    lines = ["% GENERATED by deck/scripts/make_numbers.py -- do not edit\n"]
    values = {
        "InitialSeed": initial["seed"],
        "InitialGames": initial["games"],
        "InitialStartsA": initial["starts_a"],
        "InitialStartsB": initial["starts_b"],
        "InitialWinsA": initial["wins_a"],
        "InitialWinsB": initial["wins_b"],
        "InitialTies": initial["ties"],
        "InitialRateA": pct(initial["wins_a"], initial["games"]),
        "InitialRateB": pct(initial["wins_b"], initial["games"]),
        "InitialDifference": integer(difference(initial)),
        "TargetScore": initial["target_score"],
        "StrategyA": tex_escape(initial["strategy_a"]),
        "StrategyB": tex_escape(initial["strategy_b"]),
        "BundleMinDifference": integer(min(difference(row) for row in rows)),
        "BundleMaxDifference": integer(max(difference(row) for row in rows)),
        "BundleRange": integer(max(difference(row) for row in rows) - min(difference(row) for row in rows)),
    }
    for index, row in enumerate(rows):
        suffix = row_name(index)
        values.update(
            {
                f"Seed{suffix}": row["seed"],
                f"Games{suffix}": row["games"],
                f"StartsA{suffix}": row["starts_a"],
                f"StartsB{suffix}": row["starts_b"],
                f"WinsA{suffix}": row["wins_a"],
                f"WinsB{suffix}": row["wins_b"],
                f"Ties{suffix}": row["ties"],
                f"RateA{suffix}": pct(row["wins_a"], row["games"]),
                f"RateB{suffix}": pct(row["wins_b"], row["games"]),
                f"Difference{suffix}": integer(difference(row)),
            }
        )
    for key, value in values.items():
        lines.append(f"\\newcommand{{\\{macro_name(key)}}}{{{value}}}\n")
    return "".join(lines)


def render_tables():
    initial = (
        "\\begin{tabular}{@{}rrrrrrrrr@{}}\n"
        "\\textbf{Games} & \\textbf{Starts A} & \\textbf{Starts B} & \\textbf{Wins A} & "
        "\\textbf{Wins B} & \\textbf{Ties} & \\textbf{Win A} & \\textbf{Win B} & \\textbf{A--B pp}\\\\\\midrule\n"
        "\\NInitialGames & \\NInitialStartsA & \\NInitialStartsB & \\NInitialWinsA & "
        "\\NInitialWinsB & \\NInitialTies & \\NInitialRateA & \\NInitialRateB & \\NInitialDifference\\\\\n"
        "\\end{tabular}\n"
    )
    bundle = (
        "\\begin{tabular}{@{}rrrrrrrrrr@{}}\n"
        "\\textbf{Seed} & \\textbf{Games} & \\textbf{Starts A} & \\textbf{Starts B} & "
        "\\textbf{Wins A} & \\textbf{Wins B} & \\textbf{Ties} & \\textbf{Win A} & \\textbf{Win B} & \\textbf{A--B pp}\\\\\\midrule\n"
        "\\NSeedOne & \\NGamesOne & \\NStartsAOne & \\NStartsBOne & \\NWinsAOne & \\NWinsBOne & \\NTiesOne & \\NRateAOne & \\NRateBOne & \\NDifferenceOne\\\\\n"
        "\\NSeedTwo & \\NGamesTwo & \\NStartsATwo & \\NStartsBTwo & \\NWinsATwo & \\NWinsBTwo & \\NTiesTwo & \\NRateATwo & \\NRateBTwo & \\NDifferenceTwo\\\\\n"
        "\\NSeedThree & \\NGamesThree & \\NStartsAThree & \\NStartsBThree & \\NWinsAThree & \\NWinsBThree & \\NTiesThree & \\NRateAThree & \\NRateBThree & \\NDifferenceThree\\\\\n"
        "\\end{tabular}\n"
    )
    return initial, bundle


def main():
    rows = read_rows()
    numbers = render_numbers(rows)
    initial_table, bundle_table = render_tables()
    expected = {
        DECK / "numbers.tex": numbers,
        DECK / "table_initial.tex": initial_table,
        DECK / "table_bundle.tex": bundle_table,
    }
    if "--check" in sys.argv:
        bad = [str(path) for path, text in expected.items() if not path.exists() or path.read_text() != text]
        if bad:
            print("stale generated files: " + ", ".join(bad))
            raise SystemExit(1)
        print("numbers consistent: CSV-derived macros and tables match")
        return
    for path, text in expected.items():
        path.write_text(text)
    print("wrote numbers.tex and 2 CSV-derived tables")


if __name__ == "__main__":
    main()
